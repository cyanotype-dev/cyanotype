// Package lock reads and writes cyanotype.lock, the record of what
// cyanotype generated in a project.
//
// Generated output lives in files people also write: a hand-written rule in
// .claude/settings.json looks like a generated one, and a hand edit to
// AGENTS.md looks like a newer generation. The lock records which rules
// cyanotype added and a hash of every file it generated, so regeneration can
// remove only its own rules and files, and cyanotype check can tell a hand
// edit from a change in the spec. See docs/DESIGN.md, The generated-state
// file.
//
// The lock is committed, like a package lockfile. Its output is
// deterministic: sorted, without timestamps or the tool's version, so
// regenerating an unchanged project leaves it byte for byte and merging two
// branches touches only the lines that changed.
package lock

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/cyanotype-dev/cyanotype/internal/catalog"
)

// Path is where the lock lives, relative to the project root.
const Path = "cyanotype.lock"

// Version is the lock format this cyanotype reads and writes. A lock with a
// newer version was written by a newer cyanotype, and is refused rather
// than misread.
const Version = 1

// header opens every lock. It says the same as the header of generated
// Markdown files, plus why the file must be committed.
var header = []string{
	"# Generated by cyanotype from cyanotype.yaml; regenerating replaces this file.",
	"# It records what cyanotype generated, so it can tell that apart from what",
	"# people wrote. Commit it, and do not edit it by hand.",
}

// Lock is what cyanotype generated in a project the last time it wrote it.
type Lock struct {
	// CatalogVersion is the version of the catalog the files were
	// generated with, or "" for a catalog without a manifest.
	CatalogVersion string
	// Entries maps the id of each selected entry to EntryHash of it, so
	// cyanotype check can say which entries a newer catalog changed.
	Entries map[string]string
	// Files maps the path of each generated file to Hash of the part of it
	// cyanotype owns; see render.Owned.
	Files map[string]string
	// Claude holds the permission rules cyanotype added to
	// .claude/settings.json.
	Claude Rules
}

// Rules holds the permission rules cyanotype added to each list of
// .claude/settings.json: not every rule it generates, only those that were
// not already in the file. A rule the user had before cyanotype generated
// the same rule stays the user's, so regeneration never removes it.
//
// Each list is a multiset, kept sorted: a rule cyanotype added twice, to
// keep a negation after the rules it narrows, appears twice.
type Rules struct {
	Deny []string
	Ask  []string
}

// Empty reports whether r holds no rule.
func (r Rules) Empty() bool {
	return len(r.Deny) == 0 && len(r.Ask) == 0
}

// hashPrefix names the algorithm, so it can change without breaking old
// locks.
const hashPrefix = "sha256:"

// Hash returns the hash of data as the lock records it, such as
// "sha256:3f2a…".
func Hash(data []byte) string {
	sum := sha256.Sum256(data)
	return hashPrefix + hex.EncodeToString(sum[:])
}

// validHash matches what Hash returns.
var validHash = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)

// hashedEntry holds the fields of a catalog entry that reach generated
// files. Its yaml tags omit empty fields, so a field added to the catalog
// format later changes the hash only of the entries that use it.
type hashedEntry struct {
	Name    string           `yaml:"name"`
	URL     string           `yaml:"url,omitempty"`
	Topic   string           `yaml:"topic,omitempty"`
	Snippet catalog.Snippet  `yaml:"snippet"`
	Enforce *catalog.Enforce `yaml:"enforce,omitempty"`
}

// EntryHash returns the hash of the fields of e that reach generated files:
// name, url, topic, snippet and enforce. e must be the entry as the catalog
// writes it, placeholders unfilled, so that changing an answer in
// cyanotype.yaml never looks like a change in the catalog.
func EntryHash(e catalog.Entry) (string, error) {
	data, err := yaml.Marshal(hashedEntry{Name: e.Name, URL: e.URL, Topic: e.Topic, Snippet: e.Snippet, Enforce: e.Enforce})
	if err != nil {
		return "", fmt.Errorf("hash catalog entry %s: %w", e.ID, err)
	}
	return Hash(data), nil
}

// ErrNewer reports a lock written by a newer cyanotype, in a format this
// one does not know.
var ErrNewer = errors.New("cyanotype.lock was written by a newer cyanotype; upgrade cyanotype")

// Read returns the lock at the root of project, or nil when there is none:
// a project generated before v0.3, or not generated yet.
func Read(project fs.FS) (*Lock, error) {
	if project == nil {
		return nil, nil
	}
	data, err := fs.ReadFile(project, Path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", Path, err)
	}
	return Parse(data)
}

// file is the lock as YAML holds it.
type file struct {
	Version        int               `yaml:"version"`
	CatalogVersion string            `yaml:"catalog_version"`
	Entries        map[string]string `yaml:"entries"`
	Files          map[string]string `yaml:"files"`
	Claude         struct {
		Deny []string `yaml:"deny"`
		Ask  []string `yaml:"ask"`
	} `yaml:"claude"`
}

// Parse reads a lock. Unknown fields, duplicate keys, a missing or newer
// version and malformed values are errors: the lock decides what
// regeneration removes, so a lock that cannot be read exactly is never
// guessed at.
func Parse(data []byte) (*Lock, error) {
	// The version is read first and on its own, so a newer lock is reported
	// as newer rather than as one with unknown fields.
	var v struct {
		Version int `yaml:"version"`
	}
	if err := yaml.Unmarshal(data, &v); err == nil && v.Version > Version {
		return nil, fmt.Errorf("%w (it has version %d, this cyanotype reads %d)", ErrNewer, v.Version, Version)
	}

	var f file
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&f); errors.Is(err, io.EOF) {
		return nil, invalid("it is empty")
	} else if err != nil {
		return nil, invalid(err.Error())
	}
	switch {
	case f.Version < 1:
		return nil, invalid("version must be 1 or more")
	case f.CatalogVersion != "" && !catalog.ValidVersion(f.CatalogVersion):
		return nil, invalid(fmt.Sprintf("catalog_version %q is not a catalog version", f.CatalogVersion))
	}
	for _, m := range []struct {
		name string
		hash map[string]string
	}{{"entries", f.Entries}, {"files", f.Files}} {
		for _, k := range slices.Sorted(maps.Keys(m.hash)) {
			if !validHash.MatchString(m.hash[k]) {
				return nil, invalid(fmt.Sprintf("%s.%s: %q is not a sha256 hash", m.name, k, m.hash[k]))
			}
		}
	}
	for path := range f.Files {
		if !fs.ValidPath(path) || strings.ContainsRune(path, '\\') {
			return nil, invalid(fmt.Sprintf("files: %q is not a path inside the project", path))
		}
	}
	l := &Lock{
		CatalogVersion: f.CatalogVersion,
		Entries:        f.Entries,
		Files:          f.Files,
		Claude:         Rules{Deny: f.Claude.Deny, Ask: f.Claude.Ask},
	}
	slices.Sort(l.Claude.Deny)
	slices.Sort(l.Claude.Ask)
	return l, nil
}

// ErrInvalid reports a lock that cannot be read: unknown fields, duplicate
// keys, malformed values. Errors from Read and Parse wrap it, with the
// reason, so interfaces can tell it from an I/O error.
var ErrInvalid = errors.New(Path + " is invalid")

// invalid reports a lock that cannot be read. The lock is generated, so
// the way out is to generate it again; without a lock, cyanotype treats
// every existing rule as the user's.
func invalid(reason string) error {
	return fmt.Errorf("%w: %s; it is generated, so delete it and run cyanotype generate to write it again", ErrInvalid, reason)
}

// Marshal returns the lock as it is written to disk: the header, then each
// field on its own lines, keys and rules sorted, empty fields left out.
func (l *Lock) Marshal() []byte {
	var b strings.Builder
	for _, line := range header {
		b.WriteString(line + "\n")
	}
	fmt.Fprintf(&b, "version: %d\n", Version)
	if l.CatalogVersion != "" {
		fmt.Fprintf(&b, "catalog_version: %s\n", quote(l.CatalogVersion))
	}
	writeMap(&b, "entries", l.Entries)
	writeMap(&b, "files", l.Files)
	if !l.Claude.Empty() {
		b.WriteString("claude:\n")
		writeList(&b, "deny", l.Claude.Deny)
		writeList(&b, "ask", l.Claude.Ask)
	}
	return []byte(b.String())
}

func writeMap(b *strings.Builder, key string, m map[string]string) {
	if len(m) == 0 {
		return
	}
	b.WriteString(key + ":\n")
	for _, k := range slices.Sorted(maps.Keys(m)) {
		fmt.Fprintf(b, "  %s: %s\n", plainOrQuoted(k), plainOrQuoted(m[k]))
	}
}

func writeList(b *strings.Builder, key string, items []string) {
	if len(items) == 0 {
		return
	}
	fmt.Fprintf(b, "  %s:\n", key)
	for _, item := range slices.Sorted(slices.Values(items)) {
		fmt.Fprintf(b, "    - %s\n", quote(item))
	}
}

// plain matches the strings written without quotes: ids, paths and hashes,
// whose characters mean nothing special in a YAML plain scalar. Anything
// else, such as a permission rule with spaces, is quoted.
var plain = regexp.MustCompile(`^[A-Za-z0-9._/][A-Za-z0-9._/:-]*$`)

func plainOrQuoted(s string) string {
	if plain.MatchString(s) {
		return s
	}
	return quote(s)
}

// quote returns s as a double-quoted YAML scalar. Every escape Go's
// strconv.Quote writes, such as \t or é, means the same in YAML.
func quote(s string) string {
	return strconv.Quote(s)
}
