// sample is a lock with every field set, written in a different order than
// Marshal uses, so tests also check the sorting.
func sample() *Lock {
	return &Lock{
		CatalogVersion: "2026.10.1",
		Entries: map[string]string{
			"pnpm":                    Hash([]byte("pnpm")),
			"no-destructive-commands": Hash([]byte("no-destructive-commands")),
		},
		Files: map[string]string{
			"docs/agents/testing.md": Hash([]byte("testing")),
			".gitignore":             Hash([]byte("gitignore")),
			"AGENTS.md":              Hash([]byte("agents")),
		},
		Claude: Rules{
			Deny: []string{"Read(.env)", "Bash(npm *)", "Read(!.env.example)", "Read(!.env.example)"},
			Ask:  []string{"Bash(pnpm add *)"},
		},
	}
}

func TestMarshal(t *testing.T) {
	want := `# Generated by cyanotype from cyanotype.yaml; regenerating replaces this file.
# It records what cyanotype generated, so it can tell that apart from what
# people wrote. Commit it, and do not edit it by hand.
version: 1
catalog_version: "2026.10.1"
entries:
  no-destructive-commands: ` + Hash([]byte("no-destructive-commands")) + `
  pnpm: ` + Hash([]byte("pnpm")) + `
files:
  .gitignore: ` + Hash([]byte("gitignore")) + `
  AGENTS.md: ` + Hash([]byte("agents")) + `
  docs/agents/testing.md: ` + Hash([]byte("testing")) + `
claude:
  deny:
    - "Bash(npm *)"
    - "Read(!.env.example)"
    - "Read(!.env.example)"
    - "Read(.env)"
  ask:
    - "Bash(pnpm add *)"
`
	if got := string(sample().Marshal()); got != want {
		t.Errorf("Marshal() =\n%s\nwant:\n%s", got, want)
	}
}

