// TestRoundTrip checks that Parse reads back what Marshal writes, also
// from a CRLF checkout, and that writing it again gives the same bytes.
func TestRoundTrip(t *testing.T) {
	out := sample().Marshal()
	for _, data := range [][]byte{out, []byte(strings.ReplaceAll(string(out), "\n", "\r\n"))} {
		l, err := Parse(data)
		if err != nil {
			t.Fatalf("Parse: %v", err)
		}
		if again := l.Marshal(); string(again) != string(out) {
			t.Errorf("Marshal(Parse(x)) =\n%s\nwant:\n%s", again, out)
		}
	}
}

// TestQuoting checks that values that are not ids, paths or hashes come
// back as they were written.
func TestQuoting(t *testing.T) {
	l := &Lock{
		Files:  map[string]string{"a b/#c.md": Hash(nil), "true": Hash(nil), "-x.md": Hash(nil)},
		Claude: Rules{Deny: []string{"Bash(git push *:v*)", "Edit(# x)", `Bash(echo "a\b")`, "Read(é\t)"}},
	}
	got, err := Parse(l.Marshal())
	if err != nil {
		t.Fatalf("Parse: %v\n%s", err, l.Marshal())
	}
	if string(got.Marshal()) != string(l.Marshal()) {
		t.Errorf("round trip changed the lock:\n%s\nwant:\n%s", got.Marshal(), l.Marshal())
	}
	for path := range l.Files {
		if _, ok := got.Files[path]; !ok {
			t.Errorf("file %q lost; got %v", path, got.Files)
		}
	}
}

func TestParseErrors(t *testing.T) {
	hash := Hash(nil)
	tests := []struct {
		name, in, want string
	}{
		{"empty", "", "it is empty"},
		{"no version", "catalog_version: \"2026.10\"\n", "version must be 1 or more"},
		{"unknown field", "version: 1\ntool: v0.3.0\n", "field tool not found"},
		{"duplicate key", "version: 1\nfiles:\n  AGENTS.md: " + hash + "\n  AGENTS.md: " + hash + "\n", "already defined"},
		{"bad hash", "version: 1\nfiles:\n  AGENTS.md: md5:abc\n", `files.AGENTS.md: "md5:abc" is not a sha256 hash`},
		{"bad entry hash", "version: 1\nentries:\n  go: x\n", `entries.go: "x" is not a sha256 hash`},
		{"path outside the project", "version: 1\nfiles:\n  ../AGENTS.md: " + hash + "\n", `"../AGENTS.md" is not a path inside the project`},
		{"backslash path", "version: 1\nfiles:\n  'docs\\a.md': " + hash + "\n", `is not a path inside the project`},
		{"bad catalog version", "version: 1\ncatalog_version: soon\n", `catalog_version "soon" is not a catalog version`},
		{"not yaml", "version: [1\n", "cyanotype.lock is invalid"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Parse([]byte(tt.in))
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("Parse() error = %v, want one containing %q", err, tt.want)
			}
			if !strings.Contains(err.Error(), "delete it and run cyanotype generate") {
				t.Errorf("error %q does not say how to recover", err)
			}
		})
	}
}

