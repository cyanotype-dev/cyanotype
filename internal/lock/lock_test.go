func TestRead(t *testing.T) {
	l, err := Read(fstest.MapFS{})
	if l != nil || err != nil {
		t.Errorf("Read(no lock) = %v, %v; want nil, nil", l, err)
	}
	if l, err := Read(nil); l != nil || err != nil {
		t.Errorf("Read(nil) = %v, %v; want nil, nil", l, err)
	}
	l, err = Read(fstest.MapFS{Path: {Data: sample().Marshal()}})
	if err != nil || l.CatalogVersion != "2026.10.1" || len(l.Files) != 3 {
		t.Errorf("Read() = %+v, %v", l, err)
	}
}

func TestEntryHash(t *testing.T) {
	base := catalog.Entry{
		ID: "pnpm", Name: "pnpm", Category: "package-manager", Summary: "s", Topic: "tooling",
		Snippet: catalog.Snippet{Rule: "Use pnpm for {languages}.", Why: "w"},
		Enforce: &catalog.Enforce{Claude: &catalog.ClaudeEnforce{Deny: []string{"Bash(npm *)"}}},
	}
	hash := func(e catalog.Entry) string {
		t.Helper()
		h, err := EntryHash(e)
		if err != nil {
			t.Fatal(err)
		}
		return h
	}
	want := hash(base)

	// Fields that never reach generated files do not change the hash.
	same := base
	same.Summary, same.Level, same.Category = "other", catalog.LevelBeginner, "other"
	same.Detect = &catalog.Detect{Files: []string{"pnpm-lock.yaml"}}
	if hash(same) != want {
		t.Error("summary, level, category or detect changed the hash")
	}

	for name, edit := range map[string]func(e *catalog.Entry){
		"name":    func(e *catalog.Entry) { e.Name = "PNPM" },
		"url":     func(e *catalog.Entry) { e.URL = "https://pnpm.io" },
		"topic":   func(e *catalog.Entry) { e.Topic = "git" },
		"rule":    func(e *catalog.Entry) { e.Snippet.Rule = "Use pnpm." },
		"why":     func(e *catalog.Entry) { e.Snippet.Why = "x" },
		"enforce": func(e *catalog.Entry) { e.Enforce = &catalog.Enforce{Gitignore: []string{".env"}} },
	} {
		e := base
		edit(&e)
		if hash(e) == want {
			t.Errorf("changing %s kept the hash", name)
		}
	}
}

