const mine = "# Shop\r\n\r\nUse pnpm, never npm.\r\n"

func mapFS(files map[string]string) fstest.MapFS {
	fsys := fstest.MapFS{}
	for name, content := range files {
		fsys[name] = &fstest.MapFile{Data: []byte(content)}
	}
	return fsys
}

func read(t *testing.T, fsys fs.FS, name string) string {
	t.Helper()
	data, err := fs.ReadFile(fsys, name)
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}
	return string(data)
}

func TestChoices(t *testing.T) {
	if got := Choices(); !slices.Equal(got, []Choice{Import, Keep, Move, Replace}) {
		t.Errorf("Choices() = %q", got)
	}
	for _, c := range Choices() {
		if got, err := ParseChoice(string(c)); err != nil || got != c {
			t.Errorf("ParseChoice(%q) = %q, %v", c, got, err)
		}
		if c.Writes() == (c == Import) {
			t.Errorf("%s.Writes() = %v", c, c.Writes())
		}
	}
	if _, err := ParseChoice("overwrite"); err == nil || !strings.Contains(err.Error(), "choose import, keep, move or replace") {
		t.Errorf("ParseChoice(overwrite) error = %v", err)
	}
}

func TestApplyKeep(t *testing.T) {
	view, moved, err := Apply(mapFS(map[string]string{"CLAUDE.md": mine}), map[string]Choice{"CLAUDE.md": Keep}, "CLAUDE.md", "docs/agents")
	if err != nil {
		t.Fatal(err)
	}
	want := "<!-- cyanotype:custom -->\n# Shop\n\nUse pnpm, never npm.\n<!-- /cyanotype:custom -->\n"
	if got := read(t, view, "CLAUDE.md"); got != want {
		t.Errorf("kept CLAUDE.md reads as\n%q\nwant\n%q", got, want)
	}
	if len(moved) != 0 {
		t.Errorf("keep moved %v", moved)
	}

	marked := mapFS(map[string]string{"CLAUDE.md": "# Shop\n<!-- cyanotype:custom -->\nx\n<!-- /cyanotype:custom -->\n"})
	if _, _, err := Apply(marked, map[string]Choice{"CLAUDE.md": Keep}, "CLAUDE.md", "docs/agents"); err == nil ||
		!strings.Contains(err.Error(), "already has cyanotype:custom markers") {
		t.Errorf("keeping a file with markers: error = %v", err)
	}
}

func TestApplyMove(t *testing.T) {
	pointer := "- Before starting a task, read docs/agents/original-claude.md, which holds the rules written for this project before cyanotype.\n"

	// The moved file is the main file: it reads as holding only the pointer.
	view, moved, err := Apply(mapFS(map[string]string{"CLAUDE.md": mine}), map[string]Choice{"CLAUDE.md": Move}, "CLAUDE.md", "docs/agents")
	if err != nil {
		t.Fatal(err)
	}
	want := []MovedFile{{From: "CLAUDE.md", Path: "docs/agents/original-claude.md", Content: []byte(mine)}}
	if len(moved) != 1 || moved[0].From != want[0].From || moved[0].Path != want[0].Path || string(moved[0].Content) != mine {
		t.Errorf("moved = %+v, want %+v", moved, want)
	}
	if got := read(t, view, "CLAUDE.md"); got != "## Further reading\n<!-- cyanotype:custom -->\n"+pointer+"<!-- /cyanotype:custom -->\n" {
		t.Errorf("main file reads as\n%s", got)
	}

	// CLAUDE.md only imports AGENTS.md: the pointer goes to AGENTS.md,
	// which every agent reads, after its own content.
	agents := "<!-- Generated by cyanotype -->\n\n# shop\n"
	view, _, err = Apply(mapFS(map[string]string{"CLAUDE.md": mine, "AGENTS.md": agents}), map[string]Choice{"CLAUDE.md": Move}, "AGENTS.md", "docs/agents")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := fs.ReadFile(view, "CLAUDE.md"); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("moved CLAUDE.md still reads: %v", err)
	}
	if got := read(t, view, "AGENTS.md"); !strings.HasPrefix(got, agents+"## Further reading\n") || !strings.Contains(got, pointer) {
		t.Errorf("AGENTS.md reads as\n%s", got)
	}

	taken := mapFS(map[string]string{"CLAUDE.md": mine, "docs/agents/original-claude.md": "x"})
	if _, _, err := Apply(taken, map[string]Choice{"CLAUDE.md": Move}, "CLAUDE.md", "docs/agents"); err == nil ||
		!strings.Contains(err.Error(), "docs/agents/original-claude.md: that file already exists") {
		t.Errorf("moving onto an existing file: error = %v", err)
	}
}

func TestApplyKeepAndMoveTogether(t *testing.T) {
	files := mapFS(map[string]string{"AGENTS.md": "# Rules\n", "CLAUDE.md": mine})
	view, moved, err := Apply(files, map[string]Choice{"AGENTS.md": Keep, "CLAUDE.md": Move}, "AGENTS.md", "notes")
	if err != nil {
		t.Fatal(err)
	}
	got := read(t, view, "AGENTS.md")
	if !strings.HasPrefix(got, "<!-- cyanotype:custom -->\n# Rules\n<!-- /cyanotype:custom -->\n## Further reading\n") ||
		!strings.Contains(got, "read notes/original-claude.md") {
		t.Errorf("AGENTS.md reads as\n%s", got)
	}
	if len(moved) != 1 || moved[0].Path != "notes/original-claude.md" {
		t.Errorf("moved = %+v", moved)
	}
}

func TestApplyReplaceAndImport(t *testing.T) {
	files := mapFS(map[string]string{"CLAUDE.md": mine})
	view, moved, err := Apply(files, map[string]Choice{"CLAUDE.md": Replace}, "CLAUDE.md", "docs/agents")
	if err != nil || len(moved) != 0 || read(t, view, "CLAUDE.md") != mine {
		t.Errorf("replace: moved %v, error %v; want the file read as it is", moved, err)
	}
	if _, _, err := Apply(files, map[string]Choice{"CLAUDE.md": Import}, "CLAUDE.md", "docs/agents"); err == nil {
		t.Error("import: want an error, since it writes nothing")
	}
	if _, _, err := Apply(files, map[string]Choice{"CLAUDE.md": "overwrite"}, "CLAUDE.md", "docs/agents"); err == nil {
		t.Error("unknown choice: want an error")
	}
}

func TestMovePath(t *testing.T) {
	tests := []struct{ dir, path, want string }{
		{"docs/agents", "CLAUDE.md", "docs/agents/original-claude.md"},
		{"docs/agents", "AGENTS.md", "docs/agents/original-agents.md"},
		{"docs/agents", "docs/agents/testing.md", "docs/agents/original-testing.md"},
	}
	for _, tt := range tests {
		if got := MovePath(tt.dir, tt.path); got != tt.want {
			t.Errorf("MovePath(%q, %q) = %q, want %q", tt.dir, tt.path, got, tt.want)
		}
	}
}

func TestOverlay(t *testing.T) {
	o := &overlay{base: mapFS(map[string]string{"a.md": "base", "b.md": "base"}), files: map[string][]byte{"a.md": []byte("over"), "b.md": nil}}
	if err := fstest.TestFS(&overlay{base: mapFS(map[string]string{"c.md": "c"}), files: map[string][]byte{}}, "c.md"); err != nil {
		t.Error(err)
	}
	if got := read(t, o, "a.md"); got != "over" {
		t.Errorf("a.md = %q", got)
	}
	if _, err := fs.ReadFile(o, "b.md"); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("b.md: error = %v, want ErrNotExist", err)
	}
	info, err := fs.Stat(o, "a.md")
	if err != nil || info.Size() != 4 || info.Name() != "a.md" || info.IsDir() {
		t.Errorf("Stat(a.md) = %v, %v", info, err)
	}
	empty := &overlay{files: map[string][]byte{}}
	if _, err := fs.ReadFile(empty, "x.md"); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("no base: error = %v", err)
	}
}

// TestApplyRefusalsAreTyped checks that each choice Apply cannot apply
// wraps its own error, so interfaces can name it with a code.
func TestApplyRefusalsAreTyped(t *testing.T) {
	marked := mapFS(map[string]string{"CLAUDE.md": "<!-- cyanotype:custom -->\nx\n<!-- /cyanotype:custom -->\n"})
	if _, _, err := Apply(marked, map[string]Choice{"CLAUDE.md": Keep}, "CLAUDE.md", "docs/agents"); !errors.Is(err, ErrKeepMarkers) {
		t.Errorf("keep: error = %v, want one wrapping ErrKeepMarkers", err)
	}
	taken := mapFS(map[string]string{"CLAUDE.md": mine, "docs/agents/original-claude.md": "x"})
	if _, _, err := Apply(taken, map[string]Choice{"CLAUDE.md": Move}, "CLAUDE.md", "docs/agents"); !errors.Is(err, ErrMoveExists) {
		t.Errorf("move: error = %v, want one wrapping ErrMoveExists", err)
	}
}
